/* Stage D ブートセクタ(track/sideをまたぐ複数セクタ読み込み対応)。
 *
 * IOCS $46 のレジスタ規約(D1/D2/D3/A1)は stage_c/boot/boot.S に記載の通り実測済み。
 * さらに本ステージ実装時に、境界またぎの実測実験で以下を確認した。
 *
 * 【確定したこと】
 *   - 1回の $46 呼び出しは track/side の境界をまたいで読める(実測: track0/side0/
 *     sector2起点で12000バイト=side0→side1をまたぐ読み込みが1回のTRAPで成功、
 *     チェックサム一致で確認)。
 *   - 読み進め順序は「トラック内はside0→side1、トラックは番号順に進む」
 *     (track0/side0/sector1..8 → track0/side1/sector1..8 → track1/side0/... )。
 *     px68k の disk_xdf.c の XDF_Read() の物理配置式
 *     pos=((track*2+side)*8+(sector-1))*1024 と一致する。
 *   - セクタ番号は1起点。
 *   - D0(戻り値)は「0=成功、$FFFFFFFF=エラー」だけでなく、成功時でも0以外の値
 *     (例: track2起点の単発読み込みで2、0x04000000等)を返すことがあると実測で
 *     確認した。原因は未確認だが、これらの値が返った回でもデータ自体は正しく
 *     転送されていることを実測で確認済み(転送先を毒データで埋めてから読み、期待した
 *     マーカーに置き換わることを確認)。このため本ローダのエラー判定は
 *     「D0 == $FFFFFFFF のときだけエラー」のままにしている。
 *
 * 【未解決の再現バグ(実測で確認・原因未特定のまま)】
 *   track0/side0/sector2 起点(sector1はブートセクタ自身なので使えない)で読み始め、
 *   1サイド(最大8セクタ)ごと、または1セクタごとに $46 を分割して呼ぶ実装にしたところ、
 *   **track0→track1→track2 と2回trackをまたいだ時点で read_error にはならないが
 *   起動が壊れる**(px68kが最終的にIPLの汎用エラー画面を出す = 読み込んだコードが
 *   壊れていて暴走した状態)ことを実測した。track0→track1(1回のtrack境界またぎ)
 *   までは問題なく成功する(実測: 31セクタ=track0+track1をまたぐ読み込みは成功、
 *   32セクタ=track2に到達すると失敗、を何度も再現)。
 *
 *   切り分けのため多数の実験を行った:
 *     - 最初の呼び出しを sector1 起点・8セクタ(1サイドぶんまるごと、sector1は
 *       捨てる)に変えるワークアラウンドを試したが、**このワークアラウンドは
 *       track2到達時の失敗を解決しなかった**(単独の切り分け実験では成功して
 *       見えたが、これは実験コードの転送先アドレス計算が誤っていたことによる
 *       誤った成功だったと判明した)。
 *     - D2(track/side/sector)をレジスタ演算で組み立てるか即値で与えるか、
 *       D3(バイト数)を1024固定にするか8192(1サイド分)にするか、A1(転送先)を
 *       lea直接指定にするかレジスタ間接コピーにするか、ループ内で使う残り
 *       カウンタをD7に置くかA3に置くか、を総当たりで組み合わせて単発の
 *       「track0→track1をまたぐ1回の読み込み」を検証したが、**すべての
 *       組み合わせで単独テストは成功した**(=最小構成での再現ができなかった)。
 *     - にもかかわらず、本番ブートセクタ(track0→track1→track2と実際に3トラック
 *       分をループで読み進める完全な形)では一貫して track2到達時に失敗する。
 *       単独では再現しない条件が、実際のブートセクタに組み込むと再現する
 *       ことから、原因はブートセクタ本体のサイズ/アドレスレイアウト、または
 *       それ以前の複数回の $46 呼び出しの累積状態(いずれも未特定)にあると
 *       推測されるが、**確定はできなかった**。
 *
 * 【未確認のまま残った項目(推測で埋めていない)】
 *   - 上記バグの正確な原因(IOCS内部状態か、px68kのエミュレーション上の制約か
 *     切り分けられていない)。
 *   - 1回の $46 で一度にまたげる範囲の正確な上限。
 *   - D0が0でも$FFFFFFFFでもない値(2、0x04000000等)の正確な意味。
 *
 * 【本ローダの実際の到達範囲】
 *   上記バグにより、本ローダは track0→track1 の1回のtrack境界またぎまでしか
 *   保証できない。実測で確認できた安全な本体サイズの上限は **31セクタ
 *   (31,744バイト)** で、これを超えて track2 以降へ読み進める構成は失敗する。
 *   32KB程度・256KB以上のサイズでの検証は verify/verify.mts の Stage D に
 *   組み込んであるが、**現状は失敗(FAIL)する**。ディスク全体を読み切る
 *   目標には到達できなかった。
 *
 * ビルド時に本体のセクタ数を SECTOR_COUNT として -D で埋め込む。
 * 最初の呼び出しで track0/side0/sector1 起点の8セクタ(1サイドぶん)をまとめて読み、
 * sector1ぶん(1024バイト)は使わないので $3000-1024 へ捨てる。sector2-8ぶん
 * (7セクタ)はそのまま $3000 以降へ入る。残りが必要なら track0/side1/sector1 から
 * 1セクタずつのループで続きを読み、SECTOR_COUNT セクタぶんを $3000 へ連続配置
 * してから JMP する。
 */
    .globl  _start
    .text
_start:
    bra.s   1f
    .ascii  "X68DEVD0"
1:
    lea     0xB000,%a7

    /* 最初の呼び出し: track0/side0/sector1から8セクタ(1サイドぶん)まとめて読む。
     * sector1(ブートセクタ自身の内容)ぶんは $3000-1024 = $2C00 へ捨てる。
     * sector2-8ぶん(7セクタ)は $3000 から並ぶ。 */
    move.l  #0x03000001,%d2
    move.l  #8192,%d3
    lea     0x2C00,%a1
    move.l  #0x00009070,%d1
    moveq   #0x46,%d0
    trap    #15
    cmpi.l  #-1,%d0
    beq     read_error

    move.l  #SECTOR_COUNT,%d7
    subq.l  #7,%d7               /* 最初の呼び出しでsector2-8ぶん(7セクタ)は読めている */
    ble     done                   /* 7セクタ以下ならもう不要 */

    moveq   #0,%d4                 /* track(0起点) */
    moveq   #1,%d5                  /* side(track0/side1から再開) */
    moveq   #1,%d6                   /* sector(1起点) */
    lea     0x4C00,%a2                /* = $3000 + 7*1024(既に読めたぶんの続き) */

read_loop:
    tst.l   %d7
    beq     done

    cmpi.l  #77,%d4
    bge     read_error            /* トラック上限超過(ディスク末尾を超えた) */

    /* D2 = seclen(3)<<24 | track<<16 | side<<8 | sector */
    move.l  %d4,%d2
    lsl.l   #8,%d2
    or.l    %d5,%d2
    lsl.l   #8,%d2
    or.l    %d6,%d2
    or.l    #0x03000000,%d2

    /* 実測で「D2/D3/A1をレジスタ演算で組み立てた複数セクタまとめ読み(1回で
     * 8セクタぶんなど)を、最初の特別扱い読み込みの直後から連続して行うと、
     * read_error にはならないが読み込んだ内容が壊れる」ケースを確認した
     * (原因未確認。即値で組んだ同条件の呼び出しは問題なく成功する)。
     * この安全側に倒すため、ここから先は必ず1セクタ=1024バイト固定・
     * 即値のD3で1回ずつ読む(セクタをまたぐ複数トラックの読み込みは
     * 単に呼び出し回数を増やすことで実現する)。 */
    move.l  #1024,%d3
    move.l  %a2,%a1              /* 今回の転送先 */
    move.l  #0x00009070,%d1      /* PDA=$90(FDD0), mode=$70 */
    moveq   #0x46,%d0
    trap    #15

    cmpi.l  #-1,%d0
    beq     read_error

    add.l   #1024,%a2             /* 転送先を進める */
    subq.l  #1,%d7                 /* 残りセクタ数を減らす */

    /* 次のセクタ/side/trackへ進める */
    addq.l  #1,%d6
    cmpi.l  #9,%d6
    bne     read_loop
    moveq   #1,%d6
    addq.l  #1,%d5
    cmp.l   #2,%d5
    bne     read_loop
    moveq   #0,%d5
    addq.l  #1,%d4
    bra     read_loop

done:
    jmp     0x3000

read_error:
    lea     err_msg,%a1
    moveq   #0x21,%d0
    trap    #15
halt:
    bra.s   halt

    .align 2
err_msg:
    .ascii  "STAGE D: DISK READ ERROR"
    .byte   0
