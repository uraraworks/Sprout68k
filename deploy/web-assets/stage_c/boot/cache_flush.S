/* ロード済みコードへ JMP する直前に呼ぶ、68030命令キャッシュ対策。
 *
 * 【背景】ディスクから RAM へコードを読み込んで JMP する構成では、68000 は
 * 命令キャッシュを持たないため無条件に動くが、68030(X68030)は命令キャッシュに
 * 「そのアドレス範囲の古い内容」が残っている可能性があり、読み込んだコードが
 * 正しく実行されない恐れがある。
 *
 * 【MOVEC命令の注意】キャッシュ制御レジスタ CACR を読み書きする MOVEC は
 * 68010 以降の命令で、68000 では不正命令(illegal instruction、vector 4)になる。
 * 無条件に実行すると 68000 機(ACE/EXPERT/SUPER/XVI等、標準構成)が例外で落ちる。
 * このため、まず不正命令(vector4, アドレス$10)のベクタを自前ハンドラへ
 * 差し替えてから MOVEC を試し、例外が起きたら「MOVECが使えないCPU」とみなして
 * キャッシュ操作をせずに戻る。例外が起きなければキャッシュを明示的にクリア+
 * 有効化する。
 *
 * 例外ハンドラは、例外スタックフレームの内訳(68000は6バイト固定だが68010以降は
 * フォーマット/ベクタオフセットワードが付き可変長)を一切解析しない設計にした。
 * MOVEC実行前のスーパーバイザSPを %a2 に保存しておき(メモリではなくレジスタに
 * 保持する。理由は下記)、ハンドラはそのSPをそのまま復元するだけで、フレーム
 * サイズに依存せず安全に復帰できる。
 *
 * 【実測で見つけた罠: 退避先をメモリ(ローカルラベル)にすると壊れる】
 * 最初の実装は %sp や旧ベクタ値の退避先に「このファイル内のローカルラベル」を
 * 使っていた(例: `move.l %sp,cf_saved_sp`)。これは実機/実測で **ブートセクタが
 * 完全に無応答になる(画面塗り・IOCS文字列表示のどちらも実行された形跡が無くなる)**
 * という壊れ方をした。原因はアドレッシングモード: m68k の MOVE 命令は、PC相対
 * アドレッシングを「書き込み先(destination)」には使えない(読み出し専用)。この
 * ため `move.l %sp,cf_saved_sp` はアセンブラによって暗黙に「絶対アドレス」参照に
 * なる。絶対アドレスはリンカスクリプト(`SECTIONS { . = 0x0; ... }`)が仮定する
 * 「ブートセクタは物理アドレス0にロードされる」という前提の上でしか正しく解決
 * されないが、実際のIPLはブートセクタをそれ以外の実アドレスにロードしている
 * (この既存コードベースの `boot.S` が `lea label,%aN` や分岐命令だけで書かれ、
 * 一度も `move 命令,ラベル` のような絶対アドレス書き込みを使っていないのは、
 * 恐らくこれを避けるためだったと推測される)。この罠を踏まないよう、退避には
 * メモリを一切使わずレジスタ(%a2/%a3)だけを使う設計に変更した
 * (2026-08-19、実測で発見・修正)。
 *
 * 【実機/実測状況(重要・正直に記録する)】
 * px68k(このリポジトリの検証ハーネスが使うコア)は Musashi CPU コアを CPU種別
 * 切り替えの core option 無しでビルドしており、m68k_set_cpu_type() を一度も
 * 呼んでいない。Musashi は明示的に呼ばなければ 68000 として初期化される
 * (px68k-libretro/m68000/musashi/m68k.h のコメント、および
 * px68k-libretro/m68000/musashi/m68kops.c の movec_32_rc の実装
 * (CPU_TYPE_IS_010_PLUS が偽なら即 m68ki_exception_illegal() )で確認済み)。
 * つまり本プロジェクトの検証環境では 68030 の実測は原理的に不可能で、
 * **実測できたのは「68000として不正命令例外が発生し、安全にキャッシュ操作を
 * スキップして正常続行する」経路のみ**(verify/verify.mts の全 Stage が
 * このルーチンを経由してPASSしている)。
 *
 * 68020/68030 側(MOVECが成功しCACRへ実際に書き込む経路)は、このプロジェクトの
 * 手段では一度も実行されておらず未検証。書き込む値(下記)は MC68020/68030の
 * 一般に文書化されているCACRビット割当(bit0=EI:命令キャッシュ有効化、
 * bit3=CI:命令キャッシュ全体クリア)に基づく一般的な規約であり、SRAM番地の
 * ような「本プロジェクト固有の未文書化な値」ではないが、実機やエミュレータで
 * 実測した値ではない。データキャッシュ側のビット(bit8以降)には触れない設計に
 * して、誤ったビット割当を書いた場合の影響範囲を命令キャッシュ側だけに
 * 限定してある。詳細は docs/ を参照。
 */
    .globl  cache_flush_before_jump
    .text
cache_flush_before_jump:
    /* %a2/%a3 は呼び出し元(boot.S)がこの時点でもう使っていない(ディスク読み込み
     * ループは完了済みで、この直後に $3000 へ JMP して別プログラムへ制御が
     * 移るため、呼び出し規約上のレジスタ保存は不要)。退避先はメモリではなく
     * 必ずレジスタにする(理由は上のコメント参照)。 */
    movea.l %sp,%a2                /* 例外が起きた場合の復帰用に現在のSPを保存 */
    movea.l 0x10,%a3               /* 不正命令ベクタ(vector4, アドレス$10)の元の値を保存 */
    lea     cf_illegal_handler,%a0
    move.l  %a0,0x10

    move.l  #0x00000009,%d0        /* EI(bit0)|CI(bit3): 命令キャッシュ有効化+クリア */
    movec   %d0,%cacr              /* 68000/68010ではここで不正命令例外→ハンドラへ飛ぶ */

cf_restore_vec:
    move.l  %a3,0x10                /* ベクタを元に戻す */
    rts

cf_illegal_handler:
    /* MOVECが不正命令だった(=68000相当、CACRを持たないCPU)。フレーム長を
     * 解析せず、例外前に保存しておいたSPをそのまま復元して安全に続行する。 */
    movea.l %a2,%sp
    bra     cf_restore_vec
