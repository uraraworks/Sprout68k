/* Stage E-3(rev3): メインメモリ→GVRAM 転送の3方式(word/long/movem)。
 *
 * 【rev1の欠陥】main_e3.c(rev1)は「1ワードコピーするごとに毎回 MFP GPIP
 * ($E88001)を読む」実装だった。MFP は低速な I/O バスにあり、この読み出しは
 * 2バイトのコピーそのものより遥かに高価。測っていたのは「転送速度」ではなく
 * 「転送+ワード毎ポーリング」の速度だった。
 *
 * 【rev2の欠陥】ポーリングを内側ループから分離し、コピー単位 N=4096 個ごとに
 * 1回だけ GPIP を読む形にしたが、これも誤りだった。垂直帰線期間はフレーム全体の
 * 数%程度しかなく、**ポーリング間隔が帰線期間の長さより長いと、GPIPが0に
 * なっている区間をまたいで飛び越し、立下りエッジそのものを見落とす**。
 * 見落とすと分母(検出した垂直同期回数)が過少になり、K/回数(バイト/フレーム)は
 * 大きい方向にずれる。rev2で「ポーリング間隔を増やすほど値が増え続けて収束
 * しなかった」ことも、「movemで1ロング未満のサイクル数という物理的にあり得ない
 * 値が出た」ことも、この取り逃しで説明が付く。
 *
 * rev1・rev2に共通する原因は「ゲスト側の転送ループの中で時間(垂直同期)を
 * 測ろうとしたこと」そのものだった。rev3ではこれをやめ、**ゲストのコピー
 * ループからポーリングを完全に無くす**(このファイル)。時間は
 * verify/verify_e3.mts がホスト側で runFrame() の呼び出し回数を数えることで
 * 測る(オーバーヘッドがゼロになる。ホストは自分が何回呼んだか正確に知っている
 * ので取り逃しも過剰計上も原理的に起きない)。
 *
 * 【呼び出し規約の罠(rev2で発見・修正し、rev3でも維持)】m68k の GCC ABI では
 * d2-d7/a2-a6 は呼び出され側が保存する(callee-saved)レジスタである。
 * これを退避せずに作業用レジスタとして使うと、呼び出し元(main_e3.cのfor
 * ループの繰り返し回数)がこれらのレジスタに割り付けられていた場合、
 * 2回目以降の呼び出しで破壊されて無限ループする(rev2で実際に踏んだ)。
 * rev3はR回繰り返す構成を維持しているため同じ罠を踏みうる。word/long版は
 * ポーリング撤去により a0/a1/d0(すべてcaller-saved)以外を使わなくなったので
 * 退避不要になったが、movem版は8レジスタのペイロード(d5-d7/a2-a6)を使うため
 * 引き続き退避・復帰する。
 *
 * 呼び出し規約: m68k-elf-gcc の既定(スタック渡し、cdecl相当)。
 *   4(%sp)  = dst  (GVRAM 側、vu16*)
 *   8(%sp)  = src  (メインメモリ側、vu16*)
 *  12(%sp)  = count(コピー単位の個数。word版=ワード数、long版=ロング数、
 *                    movem版=8ロング(32バイト)バッチ数)
 * 戻り値なし(rev2まであった「検出した垂直同期回数」の戻り値は廃止。
 * 時間はホスト側で測るため、ゲストが何かを数えて返す必要が無くなった)。
 */

    .globl  e3_copy_word
    .globl  e3_copy_long
    .globl  e3_copy_movem
    .text

/* ---------- word版: MOVE.W (a1)+,(a0)+ を1コピー単位とする ---------- */
e3_copy_word:
    movea.l 4(%sp),%a0
    movea.l 8(%sp),%a1
    move.l  12(%sp),%d0     /* count (words) */
wl_loop:
    tst.l   %d0
    beq.s   wl_ret
    move.w  (%a1)+,(%a0)+
    subq.l  #1,%d0
    bra.s   wl_loop
wl_ret:
    rts

/* ---------- long版: MOVE.L (a1)+,(a0)+ を1コピー単位とする ---------- */
e3_copy_long:
    movea.l 4(%sp),%a0
    movea.l 8(%sp),%a1
    move.l  12(%sp),%d0     /* count (longs) */
ll_loop:
    tst.l   %d0
    beq.s   ll_ret
    move.l  (%a1)+,(%a0)+
    subq.l  #1,%d0
    bra.s   ll_loop
ll_ret:
    rts

/* ---------- movem版: MOVEM.L で8ロング(32バイト)を1バッチとして読み書きする ----------
 * d5-d7/a2-a6(8本、callee-saved)をペイロードに使うので退避・復帰する。
 * 68000 の MOVEM はレジスタ→メモリ方向でポストインクリメント((An)+)を使えない
 * ため、ストア側は制御アドレッシング(a0)のまま書き、その後 adda.l で32バイト
 * 進める。
 */
e3_copy_movem:
    movea.l 4(%sp),%a0
    movea.l 8(%sp),%a1
    move.l  12(%sp),%d0     /* count (8ロング=32バイトのバッチ数) */
    movem.l %d5-%d7/%a2-%a6,-(%sp)
ml_loop:
    tst.l   %d0
    beq.s   ml_ret
    movem.l (%a1)+,%d5-%d7/%a2-%a6
    movem.l %d5-%d7/%a2-%a6,(%a0)
    adda.l  #32,%a0
    subq.l  #1,%d0
    bra.s   ml_loop
ml_ret:
    movem.l (%sp)+,%d5-%d7/%a2-%a6
    rts
