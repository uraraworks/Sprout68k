// Sprout68k 作例: いろいろな形を描く
//
// 絵を描くときの決まりごとは3つだけ。
//   1. x68_screen_open() で画面を開く（最初に1回だけ）
//   2. 描画関数で描く
//   3. x68_screen_flip() で画面に出す
// 3 を忘れると、いくら描いても画面は変わらない。絵が出ないときは
// まずこの3段のどれかが抜けていないかを確かめる。
//
// 座標は左上が (0, 0)、右下が (511, 511)。y は下へ行くほど大きくなる。
// 画面からはみ出した分は自動で切り取られるので、はみ出しを気にしなくてよい。

#include "x68.h"

void main(void) {
  int black = x68_rgb(0, 0, 0);
  int white = x68_rgb(255, 255, 255);
  int i;

  x68_screen_open();
  x68_cls(black);

  // 塗りつぶした四角。左から右へ色を変えていく。
  for (i = 0; i < 8; i++) {
    x68_box_fill(24 + i * 58, 40, 48, 48, x68_rgb(255 - i * 30, i * 30, 180));
  }

  // 枠だけの四角。中は塗られない。
  x68_box(24, 112, 464, 72, white);

  // 1 点から放射状に線を引く。
  for (i = 0; i < 512; i += 32) {
    x68_line(256, 296, i, 200, x68_rgb(0, 200, 255));
  }

  // 同心円。円は輪郭だけで、塗りつぶす関数は無い。
  for (i = 24; i <= 96; i += 24) {
    x68_circle(256, 384, i, x68_rgb(255, 220, 0));
  }

  // 点を 1 つずつ打って線にする。まとまった面は box_fill のほうが速い。
  for (i = 0; i < 120; i++) {
    x68_pset(24 + i, 470 + i / 8, white);
  }

  // 文字はグラフィックとは別の画面に出るので、絵の上に重なって見える。
  x68_locate(0, 0);
  printf("SHAPES");

  x68_screen_flip();
}
